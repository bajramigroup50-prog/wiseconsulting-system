/**
 * Schema — office automations: „📅 Календар на рокови“ (`rokovi`, one row per generated deadline with its status)
 * and „🧾 Месечна фактура за сметководствени услуги“ (`fee_invoices`, one row per client and month).
 * The NBRM rates live in `fx_rates` (`source = 'nbrm'`).
 */
import { boolean, date, index, integer, jsonb, numeric, pgTable, text, timestamp, uniqueIndex, uuid } from 'drizzle-orm/pg-core';
import { firms, users } from './foundation';
import { partners } from './books';
import { invoices } from './sales';

const ts = (name: string) => timestamp(name, { withTimezone: true });
const money = (name: string) => numeric(name, { precision: 18, scale: 2 });

/**
 * A deadline of a firm (generated by `@wise/core/office/rokovi` from the firm's settings, refreshed by the worker
 * `rokovi` job and by „↻ Освежи“). `key` is unique per firm (`ddv:2026-09`, `mpin:2026-09`, `doc:<id>` …).
 * `done` is set by a colleague or automatically (`auto`) when the program sees the work done.
 */
export const rokovi = pgTable('rokovi', {
  id: uuid('id').primaryKey().defaultRandom(),
  firmId: uuid('firm_id').notNull().references(() => firms.id, { onDelete: 'cascade' }),
  key: text('key').notNull(),
  type: text('type').notNull(),
  title: text('title').notNull(),
  period: text('period').notNull(),
  due: date('due').notNull(),
  /** The date in the law, before moving past a weekend / holiday. */
  legalDue: date('legal_due').notNull(),
  link: text('link').notNull(),
  /** false = „за проверка“ (date not confirmed from an official source). */
  verified: boolean('verified').notNull().default(true),
  note: text('note'),
  done: boolean('done').notNull().default(false),
  /** Marked done by the program (VAT period closed, МПИН accepted, …). */
  auto: boolean('auto').notNull().default(false),
  doneAt: ts('done_at'),
  doneBy: uuid('done_by').references(() => users.id, { onDelete: 'set null' }),
  /** No longer generated (settings changed) — kept for the history, hidden from the calendar. */
  gone: boolean('gone').notNull().default(false),
  createdAt: ts('created_at').notNull().defaultNow(),
  updatedAt: ts('updated_at').notNull().defaultNow().$onUpdate(() => new Date()),
}, (t) => [
  uniqueIndex('rokovi_firm_key_uq').on(t.firmId, t.key),
  index('rokovi_due_idx').on(t.due, t.done),
]);

/**
 * Monthly invoice of the office firm to a client for the accounting services (one per client and month — the unique
 * index makes a second click / the automatic run never bill twice). Payment comes from the office firm's bank
 * statements (`documentPayments`); `reminders` / `last_reminder` track the polite overdue reminders.
 */
export const feeInvoices = pgTable('fee_invoices', {
  id: uuid('id').primaryKey().defaultRandom(),
  officeFirmId: uuid('office_firm_id').notNull().references(() => firms.id, { onDelete: 'cascade' }),
  clientFirmId: uuid('client_firm_id').notNull().references(() => firms.id, { onDelete: 'cascade' }),
  /** `YYYY-MM` — the month of the services. */
  period: text('period').notNull(),
  invoiceId: uuid('invoice_id').references(() => invoices.id, { onDelete: 'set null' }),
  partnerId: uuid('partner_id').references(() => partners.id, { onDelete: 'set null' }),
  number: text('number'),
  date: date('date').notNull(),
  due: date('due').notNull(),
  net: money('net').notNull(),
  vat: money('vat').notNull(),
  gross: money('gross').notNull(),
  /** PDF in the client portal (inbox item of the client firm) / e-mailed. */
  portalItemId: uuid('portal_item_id'),
  mailedAt: ts('mailed_at'),
  reminders: integer('reminders').notNull().default(0),
  lastReminder: date('last_reminder'),
  /** `manual` (one click) | `auto` (billing day). */
  source: text('source').notNull().default('manual'),
  createdBy: uuid('created_by').references(() => users.id, { onDelete: 'set null' }),
  createdAt: ts('created_at').notNull().defaultNow(),
}, (t) => [
  uniqueIndex('fee_invoices_client_period_uq').on(t.clientFirmId, t.period),
  index('fee_invoices_office_idx').on(t.officeFirmId, t.period),
]);

/**
 * UX Phase 3 (P35–P38, P43): work a scheduled job PREPARED for a person to confirm — one row per automation, firm and
 * period (the unique index: a re-run updates the row, never a second one). `kind`: `close` (month ready to lock),
 * `payroll` (draft payroll run, `data.runId`), `vat` (ДДВ-04 draft), `dunning` (suggested letters). `problems` = why
 * it cannot be confirmed in bulk. `status`: `draft` → `confirmed` (by a person: locked / posted / closed) or `dismissed`.
 */
export const automationDrafts = pgTable('automation_drafts', {
  id: uuid('id').primaryKey().defaultRandom(),
  kind: text('kind').notNull(),
  firmId: uuid('firm_id').notNull().references(() => firms.id, { onDelete: 'cascade' }),
  /** `YYYY-MM`, `YYYY-Тq` or `-` (one current row per firm). */
  period: text('period').notNull(),
  status: text('status').notNull().default('draft'),
  data: jsonb('data').$type<Record<string, unknown>>().notNull().default({}),
  problems: jsonb('problems').$type<string[]>().notNull().default([]),
  createdAt: ts('created_at').notNull().defaultNow(),
  updatedAt: ts('updated_at').notNull().defaultNow().$onUpdate(() => new Date()),
  decidedAt: ts('decided_at'),
  decidedBy: uuid('decided_by').references(() => users.id, { onDelete: 'set null' }),
}, (t) => [
  uniqueIndex('automation_drafts_uq').on(t.kind, t.firmId, t.period),
  index('automation_drafts_kind_idx').on(t.kind, t.status),
]);

export type RokRow = typeof rokovi.$inferSelect;
export type AutomationDraftRow = typeof automationDrafts.$inferSelect;
export type FeeInvoiceRow = typeof feeInvoices.$inferSelect;
