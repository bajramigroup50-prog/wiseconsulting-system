const NAME = new Map(ISO_PURPOSE.map(([c, n]) => [c, n]));
/** Name of an ISO code ('' when unknown). */
export const isoPurposeName = (code: unknown): string => NAME.get(String(code ?? '').trim().toUpperCase()) ?? '';
/** A 4-letter ISO purpose code (known or not). */
export const isIsoPurpose = (code: unknown): boolean => /^[A-Z]{4}$/.test(String(code ?? '').trim().toUpperCase());

/** The ISO code for an old numeric code (or the code itself when it is already ISO); '' when unknown. */
export function isoOf(code: unknown): string {
  const c = String(code ?? '').trim().toUpperCase();
  if (!c) return '';
  if (isIsoPurpose(c)) return c;
  return OLD_TO_ISO[c.replace(/^0+(?=\d)/, '')] ?? '';
}

/** Every spelling of the same purpose: the code, its ISO code and the old codes mapped to it. */
export function purposeAliases(code: unknown): string[] {
  const c = String(code ?? '').trim().toUpperCase();
  if (!c) return [];
  const iso = isoOf(c);
  const out = new Set([c]);
  if (iso) { out.add(iso); for (const [o, i] of Object.entries(OLD_TO_ISO)) if (i === iso) out.add(o); }
  return [...out];
}

/** The statement / order code is one of these (old numbers or ISO codes, either spelling). */
export function purposeIs(code: unknown, ...codes: string[]): boolean {
  const A = purposeAliases(code);
  if (!A.length) return false;
  return codes.some((x) => A.includes(x.toUpperCase()) || purposeAliases(x).some((y) => A.includes(y) && isIsoPurpose(y)));
}

