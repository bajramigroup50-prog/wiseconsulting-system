const mk = (L: Row[], theme: SoaTheme): SoaControl[] => L.map(([id, n, a, st, j, ev, href]) => ({ id, n, theme, applicable: !!a, status: S[st]!, justification: j, evidence: ev, ...(href ? { href } : {}) }));
/** The 93 controls of ISO/IEC 27001:2022 Annex A with the proposal for an accounting office. */
export const ISO_ANNEX_A: readonly SoaControl[] = [...mk(ORG, 'org'), ...mk(PEOPLE, 'people'), ...mk(PHYS, 'physical'), ...mk(TECH, 'tech')];

/** The statement: every control with the office's confirmed entry over the proposal; `confirmed` – the office saved it. */
export function soaMerge(saved: ReadonlyMap<string, Partial<SoaEntry>>): (SoaControl & { confirmed: boolean })[] {
  return ISO_ANNEX_A.map((c) => {
    const s = saved.get(c.id);
    if (!s) return { ...c, confirmed: false };
    const applicable = typeof s.applicable === 'boolean' ? s.applicable : String(s.applicable) !== 'false';
    const status = (SOA_STATUS as readonly string[]).includes(String(s.status)) ? (s.status as SoaStatus) : c.status;
    return { ...c, applicable, status: applicable ? status : 'не се применува', justification: s.justification ?? c.justification, evidence: s.evidence ?? c.evidence, confirmed: true };
  });
}

/** Counts of the statement: confirmed, applicable, implemented / partial / planned. */
export function soaSummary(L: readonly (SoaControl & { confirmed: boolean })[]) {
  const A = L.filter((c) => c.applicable);
  return {
    total: L.length, confirmed: L.filter((c) => c.confirmed).length, applicable: A.length, excluded: L.length - A.length,
    done: A.filter((c) => c.status === 'спроведено').length, partial: A.filter((c) => c.status === 'делумно').length, planned: A.filter((c) => c.status === 'планирано').length,
    noJustification: L.filter((c) => !c.justification.trim()).length,
  };
}
