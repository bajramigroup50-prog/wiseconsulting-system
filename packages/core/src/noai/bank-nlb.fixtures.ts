/** Cyrillic item (glyph ids); width from the length unless given. */
const G = (page: number, x: number, y: number, s: string, h = 8, w?: number): PdfItem => ({ page, x, y, w: w ?? s.length * (h >= 10 ? 5.2 : 4.4), h, s: encodeGlyphText(s) });
/** Plain item (digits, Latin). */
const P = (page: number, x: number, y: number, s: string, h = 8, w?: number): PdfItem => ({ page, x, y, w: w ?? s.length * (h >= 10 ? 5.6 : 4.4), h, s });
/** Right-aligned plain amount ending at `x1`. */
const R = (page: number, x1: number, y: number, s: string, h = 8): PdfItem => { const w = s.length * (h >= 10 ? 5.0 : 4.45); return { page, x: x1 - w, y, w, h, s }; };

