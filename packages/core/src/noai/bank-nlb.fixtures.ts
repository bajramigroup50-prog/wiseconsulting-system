/**
 * SYNTHETIC text layer of an НЛБ Банка „DpsStatement“ PDF (e-banking export, one statement per file): title „Број
 * на извод: N“ / „ЗА ПРОМЕНИ НА СОСТОЈБАТА НА СРЕДСТВАТА НА СМЕТКАТА НА ДЕН dd.mm.yyyy“, balance block „Претходна
 * состојба | Дневен промет Долгува / Побарува | Нова состојба“ over the amounts, the five-line table header and
 * orders of 2–4 lines (ordinal centred, amount on the first line, the counterparty's account on the last), two pages,
 * „Вкупно денари“ and „Вкупно за сметката … има N налози“. Positions as pdfjs gives them; the Cyrillic text is in the
 * glyph ids of the embedded font (no ToUnicode map), the numbers and Latin references in a plain font — like the
 * real files. Every name, account and amount is invented.
 */
import type { PdfItem } from './pdf-lines';

/** Unicode → glyph ids of the statement font (inverse of `decodeGlyphText`). */
export function encodeGlyphText(s: string): string {
  const up = [0x401, 0x402, 0x403, 0x404, 0x405, 0x406, 0x407, 0x408, 0x409, 0x40a, 0x40b, 0x40c, 0x40e, 0x40f];
  let out = '';
  for (const ch of s) {
    const c = ch.codePointAt(0)!;
    if (c === 0x20) out += '\u0003';
    else if (c > 0x20 && c < 0x7f) out += String.fromCharCode(c - 0x1d);
    else if (c >= 0x410 && c <= 0x44f) out += String.fromCharCode(c - 0x410 + 0x23a);
    else if (up.includes(c)) out += String.fromCharCode(0x22c + up.indexOf(c));
    else if (up.includes(c - 0x50)) out += String.fromCharCode(0x27a + up.indexOf(c - 0x50));
    else out += ch;
  }
  return out;
}

